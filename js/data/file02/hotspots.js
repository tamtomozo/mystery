'use strict';

/* 同じものが複数マスにまたがるとき（ケース・ショップの棚・通用口）は、同じ act を並べる。
   きらめき（glow）は代表のマスだけに付ける */
function spots(list,act,glow){return list.map(([x,y],i)=>({x,y,act,glow:i===0?glow:undefined}));}

/* ---------- 展示室 ---------- */
function actCase(){
  if(!has('fake')){
    say(ME,'展示ケースの中に、青い宝石のブローチが収められている。');
    say(ME,'……これが「蒼の雫」。だが今朝の再鑑定で、ガラスの偽物だと分かったという。');
    say(ME,'言われなければ、本物にしか見えない。');
    give('fake');
  }else if(findable('lock')){
    say(ME,'ケースの正面に、電子錠の操作パネルがある。開閉の記録を表示させてみる。');
    sys('最後の開錠：昨日 18:00（館長のカード）　―　18:10 施錠');
    say(ME,'それ以降、ケースは一度も開けられていない……記録の上では。');
    say(ME,'鑑識によると、記録を残さずに開けられるのは、警備室にある保守用の鍵だけだそうだ。');
    give('lock');
  }else{
    say(ME,'ガラスの偽物が、何食わぬ顔で光っている。台座には重量センサーが仕込まれているそうだ。');
  }
}
function actShop(){
  if(!has('replica')){
    say(ME,'出口横のミュージアムショップ。「蒼の雫」のレプリカが並んでいる。');
    say(ME,'1点18,000円。工房に作らせたもので、ショップ用に20点あるそうだ。');
    say(ME,'……ケースの偽物と、そっくりだ。');
    give('replica');
  }else if(findable('real')){
    say(ME,'本物を隠すなら……木を隠すなら森、か。');
    say(ME,'陳列されたレプリカを、ひとつずつ数えてみる。');
    say(ME,'……21点ある。ショップ用は、20点のはずだ。');
    say(ME,'ひとつずつ手に取って比べると――ひとつだけ、ずしりと重い。');
    sys('鑑識の計量――38.2グラム。');
    say(ME,'本物の蒼の雫だ！');
    give('real');
  }else if(has('real')){
    say(ME,'本物の蒼の雫が紛れ込んでいた、レプリカの陳列。');
  }else{
    say(ME,'ずらりと並んだレプリカ。どれも同じに見える。');
  }
}
function actGalleryDoor(){
  if(phase()<2){sys('廊下では、鑑識が作業中だ。今は展示室の捜査に集中しよう。'); return;}
  ask('','廊下へ出ますか？',[
    {label:'廊下へ出る',fn:()=>fade(()=>setMap('hall',9,1,'down'))},
    {label:'やめる',fn:()=>{}}]);
}

/* ---------- 廊下：監視カメラの映像 ---------- */
// 映像を見終わった（スキップした）あとに呼ばれる。気づきがあれば物証になる
const CLIP_AFTER={
  cam2012(){
    if(findable('camera')){
      say(ME,'館長が20時12分に展示室へ入り、18分に出てくる……。');
      say(ME,'すり替えのあった20時14分は、ちょうど館長が展示室の中にいた時間だ。');
      give('camera');
    }else if(findable('flower')&&S.flags.slip){
      say(ME,'……やっぱりだ。');
      say(ME,'20時12分の映像。入口の脇に――スタンド花がない。');
      say(ME,'花は19時30分に届いて、19時32分には飾られていた。20時40分の映像にも映っている。');
      say(ME,'なのに、20時12分の映像にだけ花がない。……これは花が届く前、前の晩の映像だ！');
      give('flower');
    }
  },
  cam1932(){
    if(findable('flower')&&S.flags.slip) say(ME,'19時32分。早瀬さんが、入口の脇に花を飾っている……。20時12分の映像と比べてみよう。');
  },
};
function playClip(id){
  fade(()=>startScene(id,false,{after:CLIP_AFTER[id]}));
  return 'hold';
}
function actMonitor(){
  if(!S.flags.monitor){
    S.flags.monitor=1;
    say(ME,'警備室のモニター。展示室の入口を映すカメラの録画を、時刻を指定して再生できる。');
  }
  ask('','どの時刻の映像を見ますか？',[
    {label:'18:15',fn:()=>playClip('cam1815')},
    {label:'19:32',fn:()=>playClip('cam1932')},
    {label:'20:12',fn:()=>playClip('cam2012')},
    {label:'20:40',fn:()=>playClip('cam2040')},
    {label:'やめる',fn:()=>{}}]);
}
function actExit(){
  if(findable('exit')){
    say(ME,'職員用の通用口。出入りの記録簿が掛かっている。');
    sys('18:30 久我 退館　／　19:00 館長 退館　／　21:05 早瀬 退館（手荷物確認・異常なし　岩田）');
    say(ME,'館長は19時に出て、戻っていない。昨夜、最後まで館内に残ったのは警備員の岩田さんだけだ。');
    say(ME,'早瀬さんの手荷物も、岩田さんが帰りに確かめている……。');
    give('exit');
  }else say(ME,'職員用の通用口。出入りの記録簿が掛かっている。');
}

