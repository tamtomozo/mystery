function actRoofTrash(){
  if(!avail('cup')){say(ME,'自販機の横のゴミ箱。'); return;}
  if(!has('cup')){
    say(ME,'自販機の横のゴミ箱。「缶・びん」と「その他」に分かれている。');
    say(ME,'「その他」のほうに、くしゃくしゃに丸めた紙のかたまりがある。……中に、何か包まれている。');
    say(ME,'広げてみると――空のプリンカップと、木のスプーン。カップの底に「洋菓子 みやこ」の焼き印。');
    say(ME,'きれいに食べ尽くされている。');
    give('cup');
  }
  if(!has('memo')){
    say(ME,'カップを包んでいた紙は、手帳から破り取ったページだ。鉛筆の走り書きがある。');
    sys('「白鷺美術館　岩田 巡回 20:00〜20:35」');
    say(ME,'FILE.02の聞き込みのメモ……。この角ばった字は――滝沢さんの字だ。');
    give('memo');
  }else say(ME,'プリンのカップが捨てられていたゴミ箱。');
}

