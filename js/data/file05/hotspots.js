function f5Hole(){
  if(!has('hole')){
    say(ME,'切り株の北側に、ぽっかりと穴があいている。深さは80センチほど。');
    say(ME,'底に、丸い缶が埋まっていた跡。土に、錆の色が移っている。');
    say(ME,'二十五年前の卒業生が埋めたタイムカプセル。……ここにあったはずのものが、消えた。');
    give('hole');
  }else{
    say(ME,'空っぽの穴。底に、丸い錆の跡が残っている。');
    if(phase()>=3) say(ME,'穴のまわりの土だけ、赤い。……桜のために入れた赤土だ。');
  }
}

