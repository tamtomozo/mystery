function f6Breaker(){
  if(!has('breaker')){
    say(ME,'舞台袖の、狭い機械室。壁に、鉄の分電盤がある。');
    say(ME,'扉には南京錠。金網越しに、懐中電灯で中を照らす。');
    say(ME,'いちばん大きなレバー――主ブレーカーが、「切」の位置まで下りている。');
    say(ME,'漏電や使いすぎで落ちたなら、レバーは「切」と「入」のあいだ、「中間」で止まるはずだ。……誰かが、手で下ろした。');
    say(ME,'館じゅうの電気を止められるのは、この分電盤だけ。外からじゃない。停電は、この中で起こされた。');
    give('breaker');
  }else{
    say(ME,'分電盤。主ブレーカーは「切」のまま。南京錠がかかっていて、戻せない。');
    if(phase()>=3) say(ME,'鍵を持っているのは、二人きり。……八重子さんと、郷田さん。');
  }
}
function f6Exit(){
  if(f6Proven()){
    if(S.flags.escaped){say(ME,'開いた非常口。冷たい朝の空気が流れ込んでくる。'); return;}
    say(ME,'非常口の番号錠。赤いワイヤー錠の、4桁のダイヤル。');
    say(ME,'……郷田さんが使う番号は、何だ？');
    run(()=>openDial({answer:'0412',onOk:f6Escape,onNg:f6WrongCode}));
    return;
  }
  if(!has('padlock')){
    say(ME,'客席の右の壁に、緑の「非常口」の灯り。');
    say(ME,'押し開けるレバーと、脇の手すりが、赤いワイヤー錠でぐるぐる巻きにされている。4桁のダイヤル式だ。');
    say(ME,'錠は扉の内側――客席の側からかけてある。レバーを押しても、扉はびくともしない。');
    give('padlock');
  }else{
    say(ME,'非常口の番号錠。4桁のダイヤル。0000から9999まで、一つずつ試すには、夜が短すぎる。');
    if(phase()>=3) say(ME,'赤いワイヤー錠。……自転車に使うような錠だ。');
  }
}
function f6WrongCode(){
  sys('カチ、カチ……。錠は、開かない。');
  if(!S.flags.codeHint){
    S.flags.codeHint=1;
    say(L.tak,'郷田さんの番号か。……八重子さんなら、何か知ってるかもしれん。');
    say(L.tak,'映写日誌の一ページ目も、もう一度見ておけ。');
  }
}
// 番号錠が開いた：夜明けの外へ。そのまま取調べへ
function f6Escape(){
  S.flags.escaped=1;
  sys('カチリ。――ワイヤー錠が、ほどけて落ちた。');
  say(ME,'……開いた。');
  sys('レバーを押す。重い扉の向こうに、コンクリートの非常階段。見上げた細い空が、白みはじめている。');
  band('event',{title:'5:40',sub:'―― 夜明け',auto:2600});
  say(L.tak,'やれやれ……ひと晩ぶりの、外の空気だ。');
  say(L.tak,'郷田さん。……話は、署で聞かせてもらう。');
  say('郷田','…………。','sad');
  run(()=>goInterro());
}

