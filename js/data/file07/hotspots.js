function f7Gondola(){
  if(!has('emptyGondola')){
    say(ME,'乗り場に止められた、7番のゴンドラ。扉の外側の掛け金を外して、中をのぞく。');
    say(ME,'向かい合わせの座席が二つ。社長がバッグを置いたはずの座席の下は……空っぽだ。');
    say(ME,'掛け金は、戻ってきたとき、外側からかかったままだった。窓は、上の小窓が少し開くだけ。大人の体は、とても通らない。');
    give('emptyGondola');
  }else if(findable('seatBox')){
    say(ME,'7番の座席。……座面が、ふたになっている。持ち上げてみる。');
    say(ME,'ひざ掛けを入れておく物入れだ。中で、ひざ掛けが、誰かがくるまっていたような形にへこんでいる。');
    sys('ひざ掛けのひだに、小さな包み紙が三つ。「汐見ランド売店　いちご飴」。');
    say(ME,'ふたは、内側からも押し開けられる。……子どもなら、体を丸めれば隠れられる。');
    say(ME,'ハルさんが言っていた。坊ちゃんは、いつもポケットに「いちご飴」を入れている、と。');
    give('seatBox');
  }else if(has('seatBox')){
    say(ME,'7番の座席の下の物入れ。いちご飴の包み紙が、まだ甘い匂いをさせている。');
    if(f7Proven()) say(ME,'……社長が乗っていた12分間、湊くんは、ここにいたんだ。');
  }else{
    say(ME,'7番のゴンドラ。扉の内側には、取っ手も掛け金もない。外からしか開かない作りだ。');
    if(phase()>=2) say(ME,'窓の上の小窓。すきまは、子どもの腕なら、なんとか通るくらいか。');
  }
}
