    say(ME,'はしごを上る。看板の裏の屋上。……日が傾いて、西日が低く差しこんでいる。');
    say(ME,'砂ぼこりの上に、足跡が浮かびあがって見える。小さな運動靴。21センチくらいだ。');
    say(ME,'足跡は、ゴンドラが通るすぐそばの手すりから、屋上のまんなかの点検口まで、まっすぐ続いている。');
    say(ME,'手すりに、青い糸くずがひっかかっている。……バッグと同じ、青い化繊だ。');
    say(ME,'大人の足跡は、どこにもない。');
