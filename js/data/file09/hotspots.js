function f9Bike(){
  say(ME,'権藤さんの自転車。古い、黒い荷物用の自転車だ。前に、大きな針金のかご。');
  if(phase()>=2) sys('かごの網目に、茶色い短い毛が、一本ひっかかっている。');
  if(f9Proven()) say(ME,'……今は、ここにない。権藤さんは、これで川向こうへ出かけたらしい。');
}
